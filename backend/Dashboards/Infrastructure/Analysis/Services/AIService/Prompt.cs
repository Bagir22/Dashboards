using System.Text;

namespace Infrastructure.Analysis.Services.AIService
{
    public static class Prompt
    {
        public static string GetFromCardData(string cardData)
        {
            var sb = new StringBuilder();

            sb.AppendLine("""
                Ты — аналитик данных, который анализирует дашборды.

                Нужно сделать краткий текстовый анализ данных дашборда,
                чтобы быстро понять ключевые изменения и тенденции.

                Контекст:
                - Данные получены из карточки (card) системы Metabase.
                - Они уже учитывают применённые фильтры дашборда.
                - Данные могут быть временным рядом или агрегированными значениями.

                Твоя задача:
                1. Определи основную метрику.
                2. Найди ключевые изменения, тренды или отклонения.
                3. Отметь заметные скачки, падения или аномалии.
                4. Кратко объясни, что это может означать.

                Важно:
                - Не пересказывай все значения.
                - Сосредоточься только на значимых изменениях.
                - Не придумывай данные.
                - Если данных недостаточно для анализа — укажи это.

                Ответ должен быть кратким (3–5 предложений).

                Формат ответа:

                Краткий анализ:
                <текст 3–5 предложений>

                Ключевые наблюдения:
                - пункт
                - пункт
                """);

            sb.AppendLine();
            sb.AppendLine("Данные дашборда:");
            sb.AppendLine(cardData);

            return sb.ToString();
        }
    }
}
